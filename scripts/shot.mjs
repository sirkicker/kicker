// Usage: node scripts/shot.mjs <url> <outPrefix> [w h touch]
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const [url, out, w = "1440", h = "900", touch = "0"] = process.argv.slice(2);
const browser = await chromium.launch({ channel: "msedge" });
const ctx = await browser.newContext({ viewport: { width: +w, height: +h }, hasTouch: touch === "1", isMobile: touch === "1", deviceScaleFactor: touch === "1" ? 3 : 1 });
const page = await ctx.newPage();
const errors = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto(url, { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}-title.png` });
await page.click("text=New run");
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}-blind.png` });
await page.evaluate(() => window.kicker.game.doGo());
await page.waitForTimeout(1800);
await page.screenshot({ path: `${out}-hand.png` });
const ids = await page.evaluate(() => window.kicker.game.hint());
await page.evaluate((ids) => window.kicker.game.selectIds(ids), ids);
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}-select.png` });
await page.evaluate(() => { void window.kicker.game.doPlay(); });
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}-scoring.png` });
await page.waitForTimeout(4000);
await page.screenshot({ path: `${out}-after.png` });
console.info("errors", errors.length, errors.slice(0, 5));
const sw = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
console.info("hscroll", sw);
await browser.close();
