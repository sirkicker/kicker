// Seed UX on prod: friend's-seed button, Hall "Play this seed" deals the same as the seed link, banner text.
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const [base, out, w = "1440", h = "900", touch = "0"] = process.argv.slice(2);
const mobile = touch === "1";
const b = await chromium.launch({ channel: "msedge" });
const mk = async () => {
  const ctx = await b.newContext({ viewport: { width: +w, height: +h }, hasTouch: mobile, isMobile: mobile, deviceScaleFactor: mobile ? 3 : 1 });
  await ctx.addInitScript(() => localStorage.setItem("kk.coach", "9"));
  const p = await ctx.newPage();
  const errors = [];
  p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
  p.on("pageerror", (e) => errors.push(String(e)));
  return { p, errors, ctx };
};
const A = await mk();
await A.p.goto(base + "/", { waitUntil: "networkidle" });
await A.p.waitForTimeout(2000);
await A.p.screenshot({ path: `${out}-title.png` });
await A.p.click("text=Play a friend's seed");
await A.p.waitForTimeout(400);
console.info("seed modal text:", (await A.p.textContent(".ov-body p")).trim());
await A.p.screenshot({ path: `${out}-seedmodal.png` });
await A.p.click(".x");
await A.p.click("text=Hall of hands");
await A.p.waitForTimeout(1500);
await A.p.screenshot({ path: `${out}-hall.png` });
const n = await A.p.locator("text=Play this seed").count();
console.info("hall rows with Play this seed:", n);
await A.p.locator("text=Play this seed").first().click();
await A.p.waitForTimeout(1200);
const meta = await A.p.evaluate(() => ({ seed: window.kicker.ui.run.s.seed, ed: window.kicker.ui.run.s.edition }));
await A.p.evaluate(() => window.kicker.game.doGo());
await A.p.waitForTimeout(1600);
const handA = await A.p.evaluate(() => { const r = window.kicker.ui.run; return r.s.hand.map((i) => r.card(i).l.t).join(","); });
const banner = await A.p.evaluate(() => window.kicker.game.chalText.text);
console.info("banner:", banner);
await A.p.screenshot({ path: `${out}-hallrun.png` });
await A.p.evaluate(() => window.kicker.setUi({ overlay: "options" }));
await A.p.waitForTimeout(400);
console.info("menu shows seed:", (await A.p.textContent(".ov-body .note")).includes(meta.seed), "copy seed button:", await A.p.isVisible("text=Copy seed"));
await A.p.screenshot({ path: `${out}-menu.png` });
const B = await mk();
await B.p.goto(`${base}/?s=${meta.seed}&e=${meta.ed}`, { waitUntil: "networkidle" });
await B.p.waitForTimeout(1200);
await B.p.evaluate(() => window.kicker.game.doGo());
await B.p.waitForTimeout(1600);
const handB = await B.p.evaluate(() => { const r = window.kicker.ui.run; return r.s.hand.map((i) => r.card(i).l.t).join(","); });
console.info("hall seed", meta.seed, meta.ed, "same deal as seed link:", handA === handB && handA.length > 0);
console.info("errors", A.errors.length + B.errors.length, [...A.errors, ...B.errors].slice(0, 3), "hscroll", await A.p.evaluate(() => document.documentElement.scrollWidth - window.innerWidth));
await b.close();
